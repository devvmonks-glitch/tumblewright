-- Tumblewright database: run once on a fresh Supabase project (SQL editor, or apply as a migration).
-- Matchmaking (the public room list) and Discord voice-channel rooms use Realtime presence channels,
-- which need no tables. Everything below is: community addons, accounts, friends, presence, invites.

-- ---- slur filter used by addons and usernames ---------------------------------------------------
create or replace function public.tw_clean(t text) returns boolean language plpgsql immutable set search_path = '' as $$
declare s text;
begin
  if t is null then return true; end if;
  s := translate(lower(t), '013457@$!|', 'oieastasii');
  if regexp_replace(s, '[^a-z]', '', 'g') ~ '(n+i+g+g+(e+r+|a+|u+h+)|f+a+g+g*o+t+|w+e+t+b+a+c+k+|r+a+g+h+e+a+d+|t+o+w+e+l+h+e+a+d+|b+e+a+n+e+r+|k+i+k+e+s?$|t+r+a+n+n+(y|i+e+))' then
    return false;
  end if;
  if s ~ '(^|[^a-z])(fags?|spics?|coons?|pakis?|gooks?|dykes?|chinks?|kikes?|retards?|retarded)($|[^a-z])' then
    return false;
  end if;
  return true;
end $$;

-- ---- community addons (dupes and worlds) ---------------------------------------------------------
create table public.addons (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 40),
  author text not null check (char_length(author) between 1 and 18),
  description text not null default '' check (char_length(description) <= 240),
  kind text not null check (kind in ('dupe', 'world')),
  data jsonb not null check (pg_column_size(data) < 700000),
  objects integer not null check (objects between 1 and 900),
  downloads integer not null default 0,
  game_version text not null default '' check (char_length(game_version) <= 16),
  created_at timestamptz not null default now()
);
create index addons_created_idx on public.addons (created_at desc);
create index addons_downloads_idx on public.addons (downloads desc);
alter table public.addons enable row level security;
create policy "anyone can browse addons" on public.addons for select to anon, authenticated using (true);
create policy "anyone can upload clean addons" on public.addons for insert to anon, authenticated
  with check (public.tw_clean(name) and public.tw_clean(author) and public.tw_clean(description) and downloads = 0);

create or replace function public.addons_rate_limit() returns trigger language plpgsql set search_path = '' as $$
begin
  if (select count(*) from public.addons where created_at > now() - interval '1 minute') >= 20 then
    raise exception 'Too many uploads right now, try again in a minute';
  end if;
  return new;
end $$;
create trigger addons_rate before insert on public.addons for each row execute function public.addons_rate_limit();

create or replace function public.addon_downloaded(addon_id bigint) returns void language sql security definer set search_path = '' as $$
  update public.addons set downloads = downloads + 1 where id = addon_id;
$$;

-- ---- accounts: public profile (username + friend code); email stays private in auth.users ------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null check (username ~ '^[A-Za-z0-9_]{3,16}$' and public.tw_clean(username)),
  friend_code text not null unique default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 6)),
  created_at timestamptz not null default now()
);
create unique index profiles_username_key on public.profiles (lower(username));
alter table public.profiles enable row level security;
create policy profiles_read on public.profiles for select to anon, authenticated using (true);
create policy profiles_update_own on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
revoke insert, update, delete on public.profiles from anon, authenticated;
grant update (username) on public.profiles to authenticated;

-- the profile is created with the account (username from sign-up metadata; invalid or taken = sign-up fails)
create function public.tw_new_profile() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, username) values (new.id, new.raw_user_meta_data ->> 'username');
  return new;
end $$;
revoke execute on function public.tw_new_profile() from public, anon, authenticated;
create trigger tw_on_signup after insert on auth.users for each row execute function public.tw_new_profile();

-- ---- friendships: a asked b; b accepts --------------------------------------------------------
create table public.friends (
  a uuid not null references public.profiles(id) on delete cascade,
  b uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  primary key (a, b),
  check (a <> b)
);
create unique index friends_pair_key on public.friends (least(a, b), greatest(a, b));
create index friends_b_idx on public.friends (b);
alter table public.friends enable row level security;
create policy friends_read on public.friends for select to authenticated using ((select auth.uid()) in (a, b));
create policy friends_request on public.friends for insert to authenticated with check ((select auth.uid()) = a and status = 'pending');
create policy friends_accept on public.friends for update to authenticated using ((select auth.uid()) = b) with check ((select auth.uid()) = b and status = 'accepted');
create policy friends_remove on public.friends for delete to authenticated using ((select auth.uid()) in (a, b));
revoke all on public.friends from anon;
revoke update on public.friends from authenticated;
grant update (status) on public.friends to authenticated;

create function public.tw_friend_limit() returns trigger language plpgsql set search_path = '' as $$
begin
  if (select count(*) from public.friends where a = new.a and status = 'pending') >= 30 then
    raise exception 'Too many pending friend requests';
  end if;
  return new;
end $$;
create trigger tw_friend_limit before insert on public.friends for each row execute function public.tw_friend_limit();

create function public.tw_is_friend(other uuid) returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.friends f where f.status = 'accepted'
    and ((f.a = (select auth.uid()) and f.b = other) or (f.b = (select auth.uid()) and f.a = other)));
$$;
revoke execute on function public.tw_is_friend(uuid) from public, anon;
grant execute on function public.tw_is_friend(uuid) to authenticated;

-- ---- presence: which room you're in, readable only by accepted friends -------------------------
create table public.presence (
  id uuid primary key references public.profiles(id) on delete cascade,
  room text check (room is null or room ~ '^[A-Z0-9]{6}$'),
  mode text check (mode is null or length(mode) <= 24),
  v text check (v is null or length(v) <= 16),
  seen timestamptz not null default now()
);
alter table public.presence enable row level security;
create policy presence_read on public.presence for select to authenticated using (id = (select auth.uid()) or public.tw_is_friend(id));
create policy presence_insert on public.presence for insert to authenticated with check (id = (select auth.uid()));
create policy presence_update on public.presence for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
revoke all on public.presence from anon;
create function public.tw_touch_seen() returns trigger language plpgsql set search_path = '' as $$
begin new.seen := now(); return new; end $$;
create trigger tw_touch_seen before insert or update on public.presence for each row execute function public.tw_touch_seen();

-- ---- invites to a room: only to friends, rate limited -------------------------------------------
create table public.invites (
  id bigint generated always as identity primary key,
  from_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  to_id uuid not null references public.profiles(id) on delete cascade,
  room text not null check (room ~ '^[A-Z0-9]{6}$'),
  created_at timestamptz not null default now()
);
create index invites_to_idx on public.invites (to_id, created_at);
create index invites_from_idx on public.invites (from_id, created_at);
alter table public.invites enable row level security;
create policy invites_send on public.invites for insert to authenticated with check (from_id = (select auth.uid()) and public.tw_is_friend(to_id));
create policy invites_read on public.invites for select to authenticated using ((select auth.uid()) in (to_id, from_id));
create policy invites_clear on public.invites for delete to authenticated using ((select auth.uid()) in (to_id, from_id));
revoke all on public.invites from anon;
revoke update on public.invites from authenticated;
create function public.tw_invite_limit() returns trigger language plpgsql set search_path = '' as $$
begin
  if (select count(*) from public.invites where from_id = new.from_id and created_at > now() - interval '1 minute') >= 10 then
    raise exception 'Slow down: too many invites';
  end if;
  return new;
end $$;
create trigger tw_invite_limit before insert on public.invites for each row execute function public.tw_invite_limit();
